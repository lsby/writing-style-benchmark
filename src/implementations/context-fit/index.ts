import { 参考实现 } from '../base.js'

/**
 * Context Fit（场景适配实验方案）
 *
 * 灵感来源：
 * 受论文《Contextuality and Contradictions: Exploring Real-World Identifications of AI-Generated Writing》
 * （https://arxiv.org/abs/2611.08704v1 ）启发。该论文通过学生问卷和维基百科编辑的标注发现，
 * 读者判断一段话像不像 AI，很大程度上取决于语境——比如朋友聊天时过分中立冷淡，或百科条目里
 * 过度热情、像打广告，都会因为与场景期待不符（即“语用不协调”）而被当作 AI 特征。
 *
 * 实验目的与评估注意点：
 * 论文只研究了“人如何识别 AI”，并未验证提示词能否改善“模型生成”。本方案在生成侧做一次对照实验，
 * 测试单纯提醒模型“贴合交流场景”能否减少 AI 味。
 * 评估结果时需注意区分两种原因：一种是“没贴合场景”，另一种是“模型虽懂场景，但仍爱用高频句式、
 * 工整对仗或成套安慰话术等套路化表达”。如果加上提示后没有明显改善，也可能是原模型本身就已经适配了场景，
 * 需要结合具体文本判断，不能把所有 AI 味都归因于场景理解不足。
 *
 * 对照与实现：
 * - 对照组：与 `question-only` 保持相同的题目、公共消息格式与模型参数，均不提供参考原文和作者身份。
 * - 唯一变量：仅在“无参考。”之后追加一句场景适配提醒，不列举具体场景，也不写禁用词表。
 * - 输出方式：单次直接输出最终内容，不增加额外的场景分析或思考输出步骤。
 */
export class 场景适配实现 extends 参考实现 {
  public readonly 名称 = 'context-fit'
  public readonly 说明 =
    '参考文本声明无参考，并提醒模型让表达符合当前交流场景，直接输出最终内容；沿用不含作者身份的统一消息格式。'

  public 获取参考文本(): string {
    return '无参考。\n\n表达与当前场景不协调，会让文字显得生硬、违和。请根据当前任务，让回答的表达方式符合当前交流场景。直接输出最终内容，不附分析或创作说明。'
  }

  public override 导出配置(): Record<string, unknown> {
    return { 场景提示: this.获取参考文本() }
  }
}
