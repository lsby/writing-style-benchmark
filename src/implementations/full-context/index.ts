import { 参考实现, type 参考输入 } from '../base.js'

/**
 * Full Context（全文参考方案）
 *
 * 方案思路：
 * 作为最直接的基线参考方案，不对作者原文做任何裁剪、摘要或筛选，
 * 而是将所选作者的全部文章完整提供给模型，保留完整的语境、行文节奏与篇目结构。
 * 适合用作基准测试的对照组（观察模型拥有全部原文时的文风还原上限），
 * 或配合支持长上下文的大模型直接生成文本。
 *
 * 具体做法：
 * 1. 格式化每篇文章：遍历作者的全部文章，按 `<标题>\n<正文>` 拼接，保留篇名与篇目边界。
 * 2. 资料说明由 API 和 MCP 的公共调用方统一添加，不附加作者身份。
 *
 * 特点与取舍：
 * - 优点：实现简单，零信息损失，能完整保留作者的整体布局与长程语感。
 * - 局限：上下文长度与 Token 消耗较大，受限于模型上下文窗口大小及长文本注意力衰减。
 */
export class 全文实现 extends 参考实现 {
  public readonly 名称 = 'full-context'
  public readonly 说明 = '返回该作者的全部选文作为参考，保留篇名与篇目边界。'

  public 获取参考文本(输入: 参考输入): string {
    let 原文 = 输入.作者.文章.map((文章) => `${文章.标题}\n${文章.正文}`).join('\n\n')
    return 原文
  }
}
